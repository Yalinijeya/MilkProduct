// Converts the old C# backend's JSON files + photos into a D1 SQL file and a KV upload file.
//
//   node scripts/import-old-data.mjs [oldBackendFolder]
//   (default: "C:/Milk product/ordering-app/backend")
//
// Writes:
//   data-import/seed.sql     → npx wrangler d1 execute DB --remote --file data-import/seed.sql
//   data-import/images.json  → npx wrangler kv bulk put data-import/images.json --binding IMAGES --remote
// (npm run import:local / npm run import:remote do both.)
//
// The SQL REPLACES the items, orders and settings currently in the database.
import fs from 'node:fs';
import path from 'node:path';

const backend = path.resolve(process.argv[2] ?? 'C:/Milk product/ordering-app/backend');
const dataDir = path.join(backend, 'App_Data');
const uploadsDir = path.join(backend, 'wwwroot', 'uploads');
const outDir = path.resolve('data-import');

const readJson = (name, fallback) => {
  const file = path.join(dataDir, name);
  if (!fs.existsSync(file)) return fallback;
  return JSON.parse(fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, ''));
};

/** SQL literal */
const q = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'boolean') return v ? '1' : '0';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : '0';
  return `'${String(v).replace(/'/g, "''")}'`;
};
/** Any C# date string → the ISO format the Worker uses (2026-11-20T09:45:32.701Z). */
const iso = (s) => {
  const d = new Date(s ?? Date.now());
  return (Number.isNaN(d.getTime()) ? new Date() : d).toISOString();
};
/** C# enum names (New, OutForDelivery) → snake_case (new, out_for_delivery). */
const status = (s) =>
  String(s ?? 'new').replace(/([a-z])([A-Z])/g, '$1_$2').toLowerCase();

const items = readJson('items.json', []);
const orders = readJson('orders.json', []);
const settings = readJson('settings.json', null);

const sql = [
  '-- Generated by scripts/import-old-data.mjs from the old backend data.',
  'DELETE FROM items;',
  'DELETE FROM orders;',
];

for (const i of items) {
  sql.push(
    `INSERT INTO items (id, name, description, price, unit, image_url, available, created_at, updated_at) VALUES (` +
      [i.id, i.name, i.description ?? '', i.price, i.unit ?? '', i.imageUrl ?? '', i.available !== false, iso(i.createdAt), iso(i.updatedAt)]
        .map(q)
        .join(', ') +
      ');',
  );
}

for (const o of orders) {
  const lines = (o.items ?? []).map((l, idx) => ({
    id: l.id ?? idx + 1,
    itemId: l.itemId,
    name: l.name,
    price: l.price,
    quantity: l.quantity,
    lineTotal: l.lineTotal,
  }));
  sql.push(
    `INSERT INTO orders (id, customer_name, customer_phone, customer_address, customer_lat, customer_lng, notes, items, ` +
      `item_total, distance_km, delivery_charge, grand_total, status, whatsapp_link, whatsapp_sent, whatsapp_error, ` +
      `email_sent, email_error, created_at, updated_at) VALUES (` +
      [
        o.id, o.customerName ?? '', o.customerPhone ?? '', o.customerAddress ?? '', o.customerLat ?? 0, o.customerLng ?? 0,
        o.notes ?? '', JSON.stringify(lines), o.itemTotal ?? 0, o.distanceKm ?? 0, o.deliveryCharge ?? 0, o.grandTotal ?? 0,
        status(o.status), o.whatsAppLink ?? '', !!o.whatsAppSent, o.whatsAppError ?? '', !!o.emailSent, o.emailError ?? '',
        iso(o.createdAt), iso(o.updatedAt),
      ]
        .map(q)
        .join(', ') +
      ');',
  );
}

if (settings) {
  sql.push(
    `INSERT OR REPLACE INTO settings (id, shop_name, whatsapp_number, notify_email, shop_address, shop_lat, shop_lng, ` +
      `free_km, charge_per_km, created_at, updated_at) VALUES (1, ` +
      [
        settings.shopName ?? '', settings.whatsAppNumber ?? '', settings.notifyEmail ?? '', settings.shopAddress ?? '',
        settings.shopLat ?? 0, settings.shopLng ?? 0, settings.freeKm ?? 5, settings.chargePerKm ?? 50,
        iso(settings.createdAt), iso(settings.updatedAt),
      ]
        .map(q)
        .join(', ') +
      ');',
  );
}

// Photos used by the items → KV entries "uploads/<file>" (base64 for the bulk upload).
const images = [];
const missing = [];
for (const i of items) {
  if (!i.imageUrl?.startsWith('/uploads/')) continue;
  const name = path.basename(i.imageUrl);
  const file = path.join(uploadsDir, name);
  if (!fs.existsSync(file)) {
    missing.push(name);
    continue;
  }
  images.push({ key: `uploads/${name}`, value: fs.readFileSync(file).toString('base64'), base64: true });
}

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'seed.sql'), sql.join('\n') + '\n');
fs.writeFileSync(path.join(outDir, 'images.json'), JSON.stringify(images));

console.log(`From ${dataDir}:`);
console.log(`  ${items.length} items, ${orders.length} orders, settings: ${settings ? 'yes' : 'no'}, ${images.length} photos`);
if (missing.length) console.log(`  Photos not found (items will show no picture): ${missing.join(', ')}`);
console.log(`Wrote data-import/seed.sql and data-import/images.json`);
console.log(`Next: npm run import:local   (and later: npm run import:remote)`);
